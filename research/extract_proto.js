#!/usr/bin/env node
// Extract the serialized FileDescriptorProto embedded in a jadx-decompiled
// protobuf-java *OuterClass and print it as .proto source.
//
//   node research/extract_proto.js <OuterClass.java> [outDir]   (outDir: writes <name>.proto)
//
// protobuf-java stores the descriptor as Java string literals where each
// char is one byte (ISO-8859-1), passed to internalBuildGeneratedFileFrom().
const fs = require('fs');
const path = require('path');
const protobuf = require(path.join(__dirname, '..', 'hap', 'node_modules', 'protobufjs'));
require(path.join(__dirname, '..', 'hap', 'node_modules', 'protobufjs', 'ext', 'descriptor'));

const src = fs.readFileSync(process.argv[2], 'utf8');
const start = src.indexOf('internalBuildGeneratedFileFrom(new String[]{');
if (start < 0) throw new Error('descriptor not found');
let i = src.indexOf('{', start) + 1;

// Parse Java string literals until the closing '}' of the array.
const bytes = [];
for (;;) {
  while (/[\s,]/.test(src[i])) i++;
  if (src[i] === '}') break;
  if (src[i] !== '"') throw new Error('unexpected char ' + src[i] + ' at ' + i);
  i++;
  while (src[i] !== '"') {
    let c = src[i++];
    if (c === '\\') {
      const e = src[i++];
      if (e === 'u') { bytes.push(parseInt(src.substr(i, 4), 16) & 0xff); i += 4; continue; }
      const map = { n: 10, t: 9, r: 13, b: 8, f: 12, '"': 34, "'": 39, '\\': 92 };
      if (e in map) { bytes.push(map[e]); continue; }
      if (/[0-7]/.test(e)) { // octal escape
        let o = e; while (o.length < 3 && /[0-7]/.test(src[i])) o += src[i++];
        bytes.push(parseInt(o, 8) & 0xff); continue;
      }
      throw new Error('unknown escape \\' + e);
    }
    bytes.push(c.charCodeAt(0) & 0xff);
  }
  i++;
}

const FileDescriptorProto = protobuf.Root.fromJSON(require(path.join(__dirname, '..', 'hap', 'node_modules', 'protobufjs', 'google', 'protobuf', 'descriptor.json')))
  .lookupType('google.protobuf.FileDescriptorProto');
const fd = FileDescriptorProto.toObject(FileDescriptorProto.decode(Buffer.from(bytes)), { enums: String, defaults: false });

// ---- render .proto
const LABEL = { LABEL_REPEATED: 'repeated ' };
const TYPE = {
  TYPE_DOUBLE: 'double', TYPE_FLOAT: 'float', TYPE_INT64: 'int64', TYPE_UINT64: 'uint64',
  TYPE_INT32: 'int32', TYPE_FIXED64: 'fixed64', TYPE_FIXED32: 'fixed32', TYPE_BOOL: 'bool',
  TYPE_STRING: 'string', TYPE_BYTES: 'bytes', TYPE_UINT32: 'uint32', TYPE_SFIXED32: 'sfixed32',
  TYPE_SFIXED64: 'sfixed64', TYPE_SINT32: 'sint32', TYPE_SINT64: 'sint64',
};
const out = [];
out.push(`// Generated by research/extract_proto.js from ${path.basename(process.argv[2])}`);
out.push(`syntax = "${fd.syntax || 'proto2'}";`);
if (fd.package) out.push(`package ${fd.package};`);
for (const d of fd.dependency || []) out.push(`import "${d}";`);
out.push('');
const typeName = (f) => f.typeName ? f.typeName.replace(/^\./, '') : TYPE[f.type];
function renderEnum(e, ind) {
  out.push(`${ind}enum ${e.name} {`);
  for (const v of e.value || []) out.push(`${ind}  ${v.name} = ${v.number || 0};`);
  out.push(`${ind}}`);
}
function renderMsg(m, ind) {
  out.push(`${ind}message ${m.name} {`);
  for (const e of m.enumType || []) renderEnum(e, ind + '  ');
  for (const n of m.nestedType || []) if (!(n.options && n.options.mapEntry)) renderMsg(n, ind + '  ');
  const oneofs = (m.oneofDecl || []).map(o => ({ name: o.name, fields: [] }));
  const plain = [];
  for (const f of m.field || []) {
    const synthetic = f.proto3Optional;
    if (f.oneofIndex !== undefined && f.oneofIndex !== null && !synthetic) oneofs[f.oneofIndex].fields.push(f);
    else plain.push(f);
  }
  for (const f of plain) {
    const opt = f.proto3Optional ? 'optional ' : (LABEL[f.label] || '');
    out.push(`${ind}  ${opt}${typeName(f)} ${f.name} = ${f.number};`);
  }
  for (const o of oneofs) {
    if (!o.fields.length) continue;
    out.push(`${ind}  oneof ${o.name} {`);
    for (const f of o.fields) out.push(`${ind}    ${typeName(f)} ${f.name} = ${f.number};`);
    out.push(`${ind}  }`);
  }
  out.push(`${ind}}`);
}
for (const e of fd.enumType || []) { renderEnum(e, ''); out.push(''); }
for (const m of fd.messageType || []) { renderMsg(m, ''); out.push(''); }
const outDir = process.argv[3];
if (outDir) {
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, fd.name), out.join('\n'));
  console.log(fd.name);
} else {
  process.stdout.write(out.join('\n'));
}
